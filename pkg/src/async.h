#pragma once
#include <functional>

// Фоновые потоки для обращений к службе по HTTP: интерфейс (главный поток) никогда не ждёт сеть.
// Каждая "дорожка" (lane) - отдельный поток со своей очередью, задачи на одной дорожке идут по порядку.
//   ASYNC_LS0/ASYNC_LS1 - чтение папок левой/правой панели (новый запрос вытесняет старый)
//   ASYNC_ACT           - действия (создать папку, переименовать, запустить задание, SMB, поиск...)
//   ASYNC_POLL          - опрос состояния (прогресс заданий, очередь PKG, сканирование SMB)
enum { ASYNC_LS0 = 0, ASYNC_LS1 = 1, ASYNC_ACT = 2, ASYNC_POLL = 3, ASYNC_LANES = 4 };

void async_init();

// work выполняется в потоке дорожки; done - позже, в главном потоке, при вызове async_pump().
void async_run(int lane, std::function<void()> work, std::function<void()> done);

// Вызывать каждый кадр из главного потока: выполняет done-обработчики завершённых задач.
// Возвращает true, если хотя бы один выполнен (значит экран надо перерисовать).
bool async_pump();

// Есть ли незавершённые задачи на дорожке (для индикатора "загрузка").
bool async_pending(int lane);
